const GITHUB_OWNER = 'aami672';
const GITHUB_REPO = 'wedding-invitation';
const GITHUB_BRANCH = 'main';

function toBase64Utf8(text) {
  const bytes = new TextEncoder().encode(text);
  let binary = '';
  const chunkSize = 0x8000;
  for (let i = 0; i < bytes.length; i += chunkSize) {
    binary += String.fromCharCode(...bytes.subarray(i, i + chunkSize));
  }
  return btoa(binary);
}

async function githubRequest(path, token, options = {}) {
  const res = await fetch(`https://api.github.com/repos/${GITHUB_OWNER}/${GITHUB_REPO}${path}`, {
    ...options,
    headers: {
      Accept: 'application/vnd.github+json',
      Authorization: `Bearer ${token.trim()}`,
      'Content-Type': 'application/json',
      ...(options.headers || {}),
    },
  });

  if (!res.ok) {
    let detail = `GitHub API error (${res.status})`;
    try {
      const errBody = await res.json();
      if (errBody?.message) detail = errBody.message;
    } catch {
      // ignore non-JSON error body
    }
    if (res.status === 401) {
      throw new Error('GitHub token is invalid or expired (401).');
    }
    if (res.status === 403 || res.status === 404) {
      throw new Error(`GitHub access denied (${res.status}): ${detail}. Ensure token has Contents Read & Write permission for ${GITHUB_OWNER}/${GITHUB_REPO}.`);
    }
    throw new Error(detail);
  }

  return res.json();
}

async function commitBlobsToGitHub({ token, message, treeEntries }) {
  const ref = await githubRequest(`/git/ref/heads/${GITHUB_BRANCH}`, token);
  const baseCommitSha = ref.object.sha;
  const baseCommit = await githubRequest(`/git/commits/${baseCommitSha}`, token);
  const baseTreeSha = baseCommit.tree.sha;

  const tree = await githubRequest('/git/trees', token, {
    method: 'POST',
    body: JSON.stringify({
      base_tree: baseTreeSha,
      tree: treeEntries,
    }),
  });

  const commit = await githubRequest('/git/commits', token, {
    method: 'POST',
    body: JSON.stringify({
      message,
      tree: tree.sha,
      parents: [baseCommitSha],
    }),
  });

  await githubRequest(`/git/refs/heads/${GITHUB_BRANCH}`, token, {
    method: 'PATCH',
    body: JSON.stringify({
      sha: commit.sha,
      force: false,
    }),
  });

  return {
    commitSha: commit.sha,
    actionsUrl: `https://github.com/${GITHUB_OWNER}/${GITHUB_REPO}/actions`,
  };
}

/**
 * Commits only the client's saved JSON state to `src/data/clients/<slug>.json`.
 */
export async function saveClientToGitHub({ token, slug, data }) {
  if (!token || !token.trim()) {
    throw new Error('Missing GitHub token');
  }
  const safeSlug = (slug || 'client').replace(/[^a-zA-Z0-9._-]/g, '-');
  const jsonBlob = await githubRequest('/git/blobs', token, {
    method: 'POST',
    body: JSON.stringify({
      content: toBase64Utf8(JSON.stringify(data, null, 2)),
      encoding: 'base64',
    }),
  });

  return commitBlobsToGitHub({
    token,
    message: `Save client draft: ${safeSlug}`,
    treeEntries: [
      {
        path: `src/data/clients/${safeSlug}.json`,
        mode: '100644',
        type: 'blob',
        sha: jsonBlob.sha,
      },
    ],
  });
}

/**
 * Commits the exact standalone HTML generated by Studio (plus saved client JSON metadata)
 * directly to `main` in one atomic commit so GitHub Actions deploys the identical file.
 */
export async function publishStandaloneToGitHub({ token, slug, content, data }) {
  if (!token || !token.trim()) {
    throw new Error('Missing GitHub token');
  }

  const safeSlug = (slug || 'preeti-and-ashish').replace(/[^a-zA-Z0-9._-]/g, '-');
  const isDefaultDemo = safeSlug === 'preeti-and-ashish';
  const htmlPaths = Array.from(
    new Set([
      `public/published/${safeSlug}.html`,
      ...(isDefaultDemo
        ? ['public/published/preeti-and-ashish.html', 'public/published/index.html', 'public/preeti-and-ashish.html']
        : []),
    ])
  );

  // Upload the standalone HTML blob once and reuse its SHA across all published paths.
  const [htmlBlob, jsonBlob] = await Promise.all([
    githubRequest('/git/blobs', token, {
      method: 'POST',
      body: JSON.stringify({
        content: toBase64Utf8(content),
        encoding: 'base64',
      }),
    }),
    githubRequest('/git/blobs', token, {
      method: 'POST',
      body: JSON.stringify({
        content: toBase64Utf8(JSON.stringify(data, null, 2)),
        encoding: 'base64',
      }),
    }),
  ]);

  const blobs = [
    ...htmlPaths.map(filePath => ({
      path: filePath,
      mode: '100644',
      type: 'blob',
      sha: htmlBlob.sha,
    })),
    {
      path: `src/data/clients/${safeSlug}.json`,
      mode: '100644',
      type: 'blob',
      sha: jsonBlob.sha,
    },
    ...(isDefaultDemo
      ? [
          {
            path: 'src/data/published_invitation.json',
            mode: '100644',
            type: 'blob',
            sha: jsonBlob.sha,
          },
        ]
      : []),
  ];

  return commitBlobsToGitHub({
    token,
    message: `Publish standalone invitation: ${safeSlug}.html`,
    treeEntries: blobs,
  });
}
